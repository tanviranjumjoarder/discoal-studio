"""MCP server: lets an AI client (Claude Desktop, Claude Code, ...) design, check and run datasets.

    discoal-studio-mcp            # stdio; add it to your MCP client's config

The client fills the same typed DatasetSpec as the form; discoal commands are
always produced by the compiler. ``run_dataset`` starts a real simulation in
the background, so clients should confirm it with the user first.

Needs ``pip install "discoal-studio[mcp]"``.
"""
from __future__ import annotations

import threading
from pathlib import Path

from mcp.server.mcpserver import MCPServer
from mcp.types import ToolAnnotations
from pydantic import ValidationError

from . import __version__, analysis, assistant, engine
from .compiler import compile_one
from .runner import Runner, default_workers, pilot
from .spec import DatasetSpec, preset_descriptions, presets

DATA_ROOT = Path.home() / "discoal-studio-datasets"

server = MCPServer(
    "discoal-studio", version=__version__,
    instructions=(
        "Design, check and run discoal selective-sweep datasets. A dataset is a DatasetSpec in physical units "
        "(list_presets shows complete examples). Typical flow: list_presets or draft_spec -> check_spec -> "
        "show the user the summary and warnings -> estimate -> run_dataset only after the user agrees -> "
        "status until done -> qc."),
)


class _Run:
    runner: Runner | None = None
    thread: threading.Thread | None = None
    error: str = ""
    out: str = ""


R = _Run()


def _spec(spec: dict) -> DatasetSpec:
    try:
        return DatasetSpec.model_validate(spec)
    except ValidationError as e:
        raise ValueError("; ".join("{}: {}".format(".".join(str(x) for x in err["loc"]), err["msg"])
                                   for err in e.errors())) from e


@server.tool(annotations=ToolAnnotations(readOnlyHint=True))
def list_presets() -> dict:
    """Built-in dataset specs (including the lab's lab_ceu_sweep_2026), with descriptions and full JSON."""
    return {k: {"description": d, "spec": presets()[k].model_dump(exclude_none=True)}
            for k, d in preset_descriptions().items()}


@server.tool(annotations=ToolAnnotations(readOnlyHint=True, openWorldHint=True))
def draft_spec(prompt: str, current_spec: dict | None = None) -> dict:
    """Turn a plain-English description into a DatasetSpec using Claude (needs ANTHROPIC_API_KEY).
    Pass current_spec to edit an existing spec. Returns spec, summary, outline and warnings; runs nothing."""
    try:
        return assistant.draft(prompt, current=current_spec).as_dict()
    except assistant.AssistantError as e:
        raise ValueError(str(e)) from e


@server.tool(annotations=ToolAnnotations(readOnlyHint=True))
def check_spec(spec: dict) -> dict:
    """Validate a DatasetSpec and draw parameters for a sample of files. Returns the file count, warnings,
    a plain outline, and the first discoal command of each class (generated by the compiler)."""
    s = _spec(spec)
    _, errors, warnings = assistant.review(spec)
    return {"valid": not errors, "errors": errors, "warnings": warnings, "total_files": s.total_files,
            "outline": assistant.outline(s),
            "examples": [] if errors else [compile_one(s, c, 1).command for c in s.classes]}


@server.tool(annotations=ToolAnnotations(readOnlyHint=True))
def estimate(spec: dict, workers: int | None = None) -> dict:
    """Simulate 3 test files per class in a temporary folder and estimate time and disk for the whole dataset."""
    s = _spec(spec)
    engine.ensure(log=lambda m: None)
    return pilot(s, workers=workers)


@server.tool(annotations=ToolAnnotations(destructiveHint=False, idempotentHint=True))
def run_dataset(spec: dict, out: str = "", workers: int | None = None) -> dict:
    """Start simulating the whole dataset in the background (confirm with the user first: this can use all
    CPU cores for hours). out defaults to ~/discoal-studio-datasets/<name>. Re-running the same spec and
    folder resumes. Poll status for progress."""
    s = _spec(spec)
    if R.thread and R.thread.is_alive():
        raise ValueError(f"A run is already going into {R.out}; check status first.")
    folder = Path(out).expanduser() if out else DATA_ROOT / s.name
    R.runner = Runner(s, folder, workers=workers or default_workers(), binary=engine.ensure(log=lambda m: None))
    R.error, R.out = "", str(folder)

    def go():
        try:
            R.runner.run()
        except Exception as e:  # noqa: BLE001 - report through status
            R.error = str(e)

    R.thread = threading.Thread(target=go, daemon=True)
    R.thread.start()
    return {"started": True, "out": R.out, "files": s.total_files, "workers": R.runner.workers}


@server.tool(annotations=ToolAnnotations(readOnlyHint=True))
def status() -> dict:
    """Progress of the current or last run_dataset: done, failed, state, ETA in seconds."""
    if not R.runner:
        return {"state": "idle"}
    p = R.runner.progress.as_dict()
    if R.error:
        p.update(state="error", message=R.error)
    return {"out": R.out, **p}


@server.tool(annotations=ToolAnnotations(destructiveHint=False))
def qc(out: str) -> dict:
    """Quality check a finished dataset folder: per-class medians of segregating sites, pi, Watterson's theta,
    Tajima's D, H12, H2/H1 and haplotype count. Also writes qc_stats.csv and qc_summary.json there."""
    summary = analysis.qc(Path(out).expanduser(), workers=default_workers())
    return {cls: {k: v["median"] for k, v in stats.items()} for cls, stats in summary.items()}


def main() -> None:
    server.run()


if __name__ == "__main__":
    main()
